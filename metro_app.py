def format_route_text(path, start, end):
    """将路径转为可读文本"""
    segments = []
    cur_line = None
    seg_start = None
    for step in path:
        st, line, dist, typ = step[0], step[1], step[2], step[3]
        transfer_dist = step[4] if len(step) > 4 else 0
        if typ == 'start':
            cur_line = line
            seg_start = st
        elif typ == 'transfer':
            segments.append(f"乘{cur_line}从{seg_start}到{st}，在{st}换乘{line}(步行约{transfer_dist}米)")
            cur_line = line
            seg_start = st
    if cur_line and seg_start:
        segments.append(f"乘{cur_line}从{seg_start}到{end}")
    return "；".join(segments)


def smart_score(route):
    """无AI时的智能评分（越低越好）"""
    time_val = route.get('time', route.get('distance', 0) / SPEED_M_PER_MIN)
    return (time_val * 1.0 +
            route['transfers'] * 5 +
            route['distance'] / 1000 * 0.2)


def ai_recommend_routes(start, end, time_period=1):
    """使用AI推荐最佳路线"""
    strategies = ['shortest', 'min_transfer', 'min_fare', 'min_time']
    strategy_names = {
        'shortest': '最短距离',
        'min_transfer': '最少换乘',
        'min_fare': '最少花费',
        'min_time': '最短时间',
    }
    time_period_names = {0: '高峰', 1: '平峰', 2: '低峰'}

    # 收集所有策略的结果（去重）
    routes = []
    seen_keys = set()
    for strategy in strategies:
        result = find_path(start, end, strategy, time_period)
        if result:
            # 用路径签名去重
            sig = tuple((step[0], step[1], step[3]) for step in result['path'])
            if sig not in seen_keys:
                seen_keys.add(sig)
                result['strategy'] = strategy
                result['strategy_name'] = strategy_names[strategy]
                result['route_text'] = format_route_text(result['path'], start, end)
                # 确保有时间字段
                if 'time' not in result:
                    result['time'] = estimate_time(result)
                routes.append(result)

    if not routes:
        return None

    # 尝试调用LLM API
    llm_api_key = os.environ.get('LLM_API_KEY', '')
    llm_api_base = os.environ.get('LLM_API_BASE', 'https://api.deepseek.com/v1')
    llm_model = os.environ.get('LLM_MODEL', 'deepseek-chat')

    if llm_api_key:
        try:
            recommendation = call_llm_recommend(start, end, routes, time_period_names[time_period],
                                                llm_api_key, llm_api_base, llm_model)
            if recommendation:
                return {
                    "recommendation": recommendation,
                    "ai_powered": True,
                    "routes": routes,
                    "time_period": time_period_names[time_period],
                }
        except Exception as e:
            print(f"LLM API调用失败: {e}，回退到规则评分")

    # 回退：规则评分
    best_route = min(routes, key=smart_score)
    return {
        "recommendation": generate_rule_based_recommendation(routes, best_route, time_period_names[time_period]),
        "ai_powered": False,
        "routes": routes,
        "best_route_idx": routes.index(best_route),
        "time_period": time_period_names[time_period],
    }


def estimate_time(result):
    """估算非min_time策略的时间"""
    total_time = 0
    # 行驶时间
    total_time += result['distance'] / SPEED_M_PER_MIN
    # 换乘步行时间
    total_time += result['transfers'] * 300 / WALK_SPEED_M_PER_MIN
    # 等待时间（假设每次换乘等平峰5分钟的一半）
    total_time += (result['transfers'] + 1) * 2.5
    return total_time


